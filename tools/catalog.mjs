// Generates docs/COMPONENTS.md and docs/catalog.json from the package's public exports: every component, hook,
// helper, and type, with its doc comment, Plumb-specific props (inherited React Aria props are omitted), and source file. Run after changing exports
// (`pnpm catalog`); CI fails if the committed files are out of date (`pnpm catalog --check`).
import ts from "typescript";
import { readFile, writeFile } from "node:fs/promises";

const program = ts.createProgram(["src/index.ts"], { jsx: ts.JsxEmit.ReactJSX, module: ts.ModuleKind.ESNext, moduleResolution: ts.ModuleResolutionKind.Bundler, resolveJsonModule: true, skipLibCheck: true, strict: true, target: ts.ScriptTarget.ES2022 });
const checker = program.getTypeChecker();
const entry = checker.getSymbolAtLocation(program.getSourceFile("src/index.ts"));
const doc = (s) => ts.displayPartsToString(s.getDocumentationComment(checker)).replace(/\s+/g, " ").trim();
const groups = { components: "Foundations and generic components", lib: "Foundations and generic components", patterns: "Framed patterns", features: "Framed patterns" };

const items = checker.getExportsOfModule(entry).map((sym) => {
  const target = sym.flags & ts.SymbolFlags.Alias ? checker.getAliasedSymbol(sym) : sym;
  const decl = target.declarations?.[0];
  const file = decl?.getSourceFile().fileName.replace(/^.*?src\//, "src/") ?? "";
  const isType = !!(target.flags & (ts.SymbolFlags.Interface | ts.SymbolFlags.TypeAlias));
  const isFn = !!(target.flags & ts.SymbolFlags.Function) || (decl && ts.isVariableDeclaration(decl) && decl.initializer && ts.isArrowFunction(decl.initializer));
  const name = sym.getName();
  const kind = isType ? "type" : /^use[A-Z]/.test(name) ? "hook" : isFn && /^[A-Z]/.test(name) ? "component" : isFn ? "function" : "value";
  let props;
  if (kind === "component" && decl) {
    const sig = checker.getSignaturesOfType(checker.getTypeOfSymbolAtLocation(target, decl), ts.SignatureKind.Call)[0];
    const param = sig?.getParameters()[0];
    if (param) {
      const type = checker.getTypeOfSymbolAtLocation(param, decl);
      props = type.getProperties().map((p) => {
        const pd = p.declarations?.[0];
        return { name: p.getName(), optional: !!(p.flags & ts.SymbolFlags.Optional), type: pd ? checker.typeToString(checker.getTypeOfSymbolAtLocation(p, pd)).slice(0, 120) : "", doc: doc(p) };
      }).filter((_, i, all) => all[i] && type.getProperties()[i].declarations?.some((d) => !d.getSourceFile().fileName.includes("node_modules")));
    }
  }
  return { name, kind, file, group: groups[file.split("/")[1]] ?? "Other", summary: doc(target), ...(props ? { props } : {}) };
}).sort((a, b) => a.file.localeCompare(b.file) || a.name.localeCompare(b.name));

const md = [`# Component catalogue`, "", `Generated by \`pnpm catalog\` from \`src/index.ts\`. Don't edit by hand. Props and examples: Storybook and the TypeScript declarations.`, ""];
for (const g of new Set(Object.values(groups))) {
  md.push(`## ${g}`, "");
  let file = "";
  for (const i of items.filter((x) => x.group === g && x.kind !== "type")) {
    if (i.file !== file) { file = i.file; md.push("", `### \`${file}\``, "", "| Export | Kind | What it's for |", "| --- | --- | --- |"); }
    md.push(`| \`${i.name}\` | ${i.kind} | ${i.summary.replace(/\|/g, "\\|") || "—"} |`);
  }
  md.push("");
}
const counts = Object.fromEntries(["component", "hook", "function", "type", "value"].map((k) => [k, items.filter((i) => i.kind === k).length]));
md.push(`---`, ``, `${counts.component} components · ${counts.hook} hooks · ${counts.function} functions · ${counts.value} values · ${counts.type} types.`, "");
const json = JSON.stringify({ package: JSON.parse(await readFile("package.json", "utf8")).name, items }, null, 2) + "\n";

if (process.argv.includes("--check")) {
  const same = (await readFile("docs/COMPONENTS.md", "utf8").catch(() => "")) === md.join("\n") && (await readFile("docs/catalog.json", "utf8").catch(() => "")) === json;
  if (!same) { console.error("docs/COMPONENTS.md or docs/catalog.json is out of date; run `pnpm catalog`."); process.exit(1); }
  console.log("catalogue up to date");
} else {
  await writeFile("docs/COMPONENTS.md", md.join("\n"));
  await writeFile("docs/catalog.json", json);
  console.log(`catalogue: ${JSON.stringify(counts)}`);
}
